create table if not exists public.brother_etc_docs (
  id            bigint generated by default as identity primary key,
  task_id       bigint not null references public.brother_tasks(id) on delete cascade,
  storage_path  text not null,
  file_name     text not null,
  file_size     bigint,
  uploaded_at   timestamptz not null default now()
);

create table if not exists public.brother_holds (
  id            bigint generated by default as identity primary key,
  record_id     text not null,
  scheduled_at  timestamptz not null,
  note          text,
  recipients    text[] not null default '{}',
  is_sent       boolean not null default false,
  created_at    timestamptz not null default now(),
  unique (record_id)
);

create table if not exists public.brother_vehicle_reg_doc_uploads (
  id            uuid primary key default gen_random_uuid(),
  record_id     text not null,
  uploaded_by   uuid not null,
  storage_path  text not null,
  file_name     text not null,
  file_size     bigint,
  uploaded_at   timestamptz not null default now(),
  expires_at    timestamptz not null default now() + interval '72:00:00'
);

create table if not exists public.brother_tax_invoice_uploads (
  id            uuid primary key default gen_random_uuid(),
  record_id     text not null,
  uploaded_by   uuid not null,
  storage_path  text not null,
  file_name     text not null,
  file_size     bigint,
  invoice_type  text not null default 'vehicle',
  uploaded_at   timestamptz not null default now(),
  expires_at    timestamptz not null default now() + interval '72:00:00'
);

-- ── 3) RLS ────────────────────────────────────────────────
alter table public.brother_tasks enable row level security;
alter table public.brother_etc_docs enable row level security;
alter table public.brother_holds enable row level security;
alter table public.brother_vehicle_reg_doc_uploads enable row level security;
alter table public.brother_tax_invoice_uploads enable row level security;

revoke all on public.brother_tasks from anon;
revoke all on public.brother_etc_docs from anon;
revoke all on public.brother_holds from anon;
revoke all on public.brother_vehicle_reg_doc_uploads from anon;
revoke all on public.brother_tax_invoice_uploads from anon;

create policy brother_tasks_select on public.brother_tasks for select
  using (
    public.is_brother_staff()
    and not (coalesce(skip_sales_rep_alert, false) and public.is_brother_sales_rep())
  );
create policy brother_tasks_insert on public.brother_tasks for insert
  with check (public.is_brother_staff());
create policy brother_tasks_update on public.brother_tasks for update
  using (
    public.is_brother_staff()
    and not (coalesce(skip_sales_rep_alert, false) and public.is_brother_sales_rep())
  )
  with check (
    public.is_brother_staff()
    and not (coalesce(skip_sales_rep_alert, false) and public.is_brother_sales_rep())
  );
create policy brother_tasks_delete on public.brother_tasks for delete
  using (public.is_admin_level());

create policy brother_etc_docs_select on public.brother_etc_docs for select using (public.is_brother_staff());
create policy brother_etc_docs_insert on public.brother_etc_docs for insert with check (public.is_brother_staff());
create policy brother_etc_docs_update on public.brother_etc_docs for update using (public.is_brother_staff()) with check (public.is_brother_staff());
create policy brother_etc_docs_delete on public.brother_etc_docs for delete using (public.is_brother_staff());

create policy brother_holds_all on public.brother_holds for all
  using (public.is_brother_staff()) with check (public.is_brother_staff());

create policy brother_vehicle_reg_doc_uploads_select on public.brother_vehicle_reg_doc_uploads for select using (public.is_brother_staff());
create policy brother_vehicle_reg_doc_uploads_insert on public.brother_vehicle_reg_doc_uploads for insert with check (public.is_brother_staff());
create policy brother_vehicle_reg_doc_uploads_update on public.brother_vehicle_reg_doc_uploads for update using (public.is_brother_staff()) with check (public.is_brother_staff());
create policy brother_vehicle_reg_doc_uploads_delete on public.brother_vehicle_reg_doc_uploads for delete using (public.is_admin_level());

create policy brother_tax_invoice_uploads_all on public.brother_tax_invoice_uploads for all
  using (public.is_brother_staff()) with check (public.is_brother_staff());

