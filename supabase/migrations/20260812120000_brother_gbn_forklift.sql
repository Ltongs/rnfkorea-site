-- ── 1) 역할 헬퍼 함수 ──────────────────────────────────────
create or replace function public.is_brother_staff()
returns boolean language sql stable as $$
  select public.is_admin_level() or coalesce((auth.jwt()->>'email'), '') = 'hj5321006@naver.com';
$$;

create or replace function public.is_brother_sales_rep()
returns boolean language sql stable as $$
  select coalesce((auth.jwt()->>'email'), '') = 'hj5321006@naver.com';
$$;

