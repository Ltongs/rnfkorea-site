-- 데이터가 없는 미래 연도는 주말/업무시간(09~19시) 판정만 적용되고, 공휴일 판정은 자동 생략됩니다.
create table if not exists kr_holidays (
  holiday_date date primary key,
  name text not null
);

alter table kr_holidays enable row level security;
create policy "public_read_kr_holidays" on kr_holidays for select using (true);

