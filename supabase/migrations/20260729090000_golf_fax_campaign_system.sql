-- 골프장 팩스 자동발송 시스템
-- 골프카트 배터리 브로셔를 서울경기/부산경남/대구경북 골프장에 정기적으로 팩스 발송하기 위한
-- 마스터 연락처/캠페인/발송이력 테이블 + 초기 데이터(231곳) + 월간 발송 트리거 cron.
-- 이미 카카오 알림톡/SMS에 쓰고 있는 Solapi 계정(SOLAPI_API_KEY/SOLAPI_API_SECRET/SOLAPI_SENDER_NUMBER)을 재사용한다.

-- ─── 1. 골프장 연락처 마스터 ───────────────────────────────────
create table public.golf_course_contacts (
  id uuid primary key default gen_random_uuid(),
  region text not null,
  name text not null,
  address text,
  phone text,
  fax text,
  holes_type text,
  homepage text,
  note text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index golf_course_contacts_region_idx on public.golf_course_contacts (region);
create index golf_course_contacts_is_active_idx on public.golf_course_contacts (is_active);

create or replace function public.set_golf_course_contacts_updated_at()
returns trigger
language plpgsql
as $function$
begin
  new.updated_at := now();
  return new;
end;
$function$;

create trigger golf_course_contacts_set_updated_at
  before update on public.golf_course_contacts
  for each row execute function public.set_golf_course_contacts_updated_at();

-- ─── 2. 팩스 캠페인(발송 회차) ───────────────────────────────
create table public.fax_campaigns (
  id uuid primary key default gen_random_uuid(),
  campaign_name text not null,
  file_id text,
  target_region text,
  scheduled_at timestamptz,
  status text not null default 'draft',
  created_at timestamptz not null default now()
);

create index fax_campaigns_status_idx on public.fax_campaigns (status);

-- ─── 3. 발송 이력 ───────────────────────────────────────────
create table public.fax_send_log (
  id uuid primary key default gen_random_uuid(),
  campaign_id uuid not null references public.fax_campaigns(id),
  contact_id uuid not null references public.golf_course_contacts(id),
  fax_number text not null,
  solapi_message_id text,
  status text not null default 'pending',
  error_message text,
  sent_at timestamptz,
  created_at timestamptz not null default now()
);

create index fax_send_log_campaign_id_idx on public.fax_send_log (campaign_id);
create index fax_send_log_contact_id_idx on public.fax_send_log (contact_id);
create unique index fax_send_log_campaign_contact_uniq on public.fax_send_log (campaign_id, contact_id);

-- ─── 4. RLS: 관리자급만 접근 (기존 is_admin_level() 헬퍼 재사용) ───
alter table public.golf_course_contacts enable row level security;
alter table public.fax_campaigns enable row level security;
alter table public.fax_send_log enable row level security;

create policy golf_course_contacts_admin_all on public.golf_course_contacts
  for all using (public.is_admin_level()) with check (public.is_admin_level());

create policy fax_campaigns_admin_all on public.fax_campaigns
  for all using (public.is_admin_level()) with check (public.is_admin_level());

create policy fax_send_log_admin_all on public.fax_send_log
  for all using (public.is_admin_level()) with check (public.is_admin_level());

-- ─── 5. 월간 정기 발송 트리거 함수 ───────────────────────────
-- status='scheduled'인 최신 캠페인이 있을 때만 send-fax-campaign을 호출한다.
-- (scheduled 캠페인이 없으면 조용히 종료 — 담당자가 매번 수동으로 캠페인을 만들어야
--  실제 발송이 이뤄지는 안전장치. clear_expired_narumi_data()와 동일한 wrapping-function 패턴)
-- net.http_post 호출은 다른 기존 cron들(gmail-report-daily 등)과 동일하게 프로젝트 anon key를
-- 그대로 사용한다 — service_role_key는 시크릿이라 마이그레이션 파일에 남기지 않는다.
