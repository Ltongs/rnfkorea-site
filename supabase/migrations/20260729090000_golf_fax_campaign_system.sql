as $function$
declare
  v_campaign_id uuid;
begin
  select id into v_campaign_id
  from public.fax_campaigns
  where status = 'scheduled'
  order by created_at desc
  limit 1;

  if v_campaign_id is null then
    return;
  end if;

  perform net.http_post(
